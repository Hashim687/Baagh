"""Business reports: GST-aware invoice ledger and an Excel workbook laid out for Tally and GSTR-1.

Everything is computed from accepted orders. Invoice numbers (BG/26-27/00012) are generated by Baagh as a
reference per order; they are not a substitute for a seller's own GST invoice series.
"""
from __future__ import annotations

import io
from collections import OrderedDict, defaultdict
from datetime import date, datetime, timezone
from decimal import Decimal

from openpyxl import Workbook
from openpyxl.styles import Alignment, Border, Font, PatternFill, Side
from openpyxl.utils import get_column_letter

import catalog
import geo
import gst

B2CL_THRESHOLD = Decimal("100000")  # Notification 12/2024-CT, effective 1 Aug 2024
DISCLAIMER = ("Generated from Baagh order data. GST rates are defaults (rates effective 22-Sep-2025). "
              "This is a working report, not tax advice: have a Chartered Accountant check rates, place of supply "
              "and registration status before filing returns.")


# ------------------------------------------------------------------ invoice builder
def _resolve_tax_defaults(row) -> tuple[str, Decimal, str]:
    crop = row["crop"]
    form = row["product_form"] or (catalog.default_form(crop) if catalog.get_crop(crop) else "")
    info = catalog.form_info(crop, form) or {}
    hsn = row["o_hsn"] or row["l_hsn"] or info.get("hsn", "")
    rate = row["o_rate"] if row["o_rate"] is not None else (row["l_rate"] if row["l_rate"] is not None else info.get("gst_rate", 0))
    return hsn or "", gst.d(rate), form


def collect_invoices(conn, user: dict, start: date | None, end: date | None) -> list[dict]:
    role = user["role"]
    col = "o.seller_id" if role == "seller" else "o.buyer_id"
    rows = conn.execute(f"""
        SELECT o.id, o.quantity_kg, o.price_per_kg, o.status, o.created_at, o.dispatched_at, o.delivered_at,
               o.hsn_code AS o_hsn, o.gst_rate AS o_rate,
               l.crop, l.variety, l.product_form, l.grade, l.grade_label, l.hsn_code AS l_hsn, l.gst_rate AS l_rate,
               s.name AS sname, s.member_code AS scode, s.gstin AS sgstin, s.state AS sstate, s.country AS scountry,
               s.district AS sdistrict, s.pincode AS spin,
               b.name AS bname, b.member_code AS bcode, b.gstin AS bgstin, b.state AS bstate, b.country AS bcountry,
               b.district AS bdistrict, b.pincode AS bpin
        FROM orders o JOIN listings l ON l.id=o.listing_id
        JOIN users s ON s.id=o.seller_id JOIN users b ON b.id=o.buyer_id
        WHERE {col}=? ORDER BY o.created_at, o.id""", (user["id"],)).fetchall()
    invoices = []
    for r in rows:
        basis_ts = r["dispatched_at"] or r["created_at"]
        inv_date = gst.to_ist_date(basis_ts)
        if (start and inv_date < start) or (end and inv_date > end):
            continue
        hsn, rate, form = _resolve_tax_defaults(r)
        sgstin = (r["sgstin"] or "").strip()
        bgstin = (r["bgstin"] or "").strip()
        s_state = geo.canonical_state(r["sstate"] or "") or geo.JK_STATE
        s_code = gst.gstin_state_code(sgstin) or geo.GST_STATE_CODES.get(s_state, "")
        export = (r["bcountry"] or "IN").upper() != "IN"
        b_state = "Foreign Country" if export else (geo.canonical_state(r["bstate"] or "") or "")
        pos_code = "96" if export else (gst.gstin_state_code(bgstin) or geo.GST_STATE_CODES.get(b_state, ""))
        qty = gst.d(r["quantity_kg"])
        price = gst.d(r["price_per_kg"])
        taxable = gst.money(qty * price)
        tax = gst.compute_tax(taxable, rate, s_code, pos_code, supplier_registered=bool(sgstin), export=export)
        status = r["status"]
        basis = {"Delivered": "Delivered", "In transit": "Dispatched"}.get(status, "Provisional (accepted, not yet dispatched)")
        label = r["grade_label"] or catalog.grade_label_for(r["crop"], r["grade"])
        item = f"{r['crop']} - {r['variety']}" + (f" - {form}" if form else "") + f", {label} grade"
        fy = gst.fy_for_date(inv_date)
        invoices.append({
            "order_id": r["id"], "date": inv_date, "fy": fy,
            "invoice_no": f"BG/{fy[2:]}/{r['id']:05d}", "status": status, "basis": basis,
            "item": item, "crop": r["crop"], "hsn": hsn, "qty": qty, "price": price,
            "seller": r["sname"], "seller_code": r["scode"], "seller_gstin": sgstin, "seller_state": s_state,
            "seller_state_code": s_code,
            "buyer": r["bname"], "buyer_code": r["bcode"], "buyer_gstin": bgstin, "buyer_state": b_state,
            "buyer_country": (r["bcountry"] or "IN").upper(), "pos_code": pos_code,
            "pos_label": f"{pos_code}-{b_state}" if pos_code and b_state else (pos_code or "Not provided"),
            "export": export, "tax": tax,
        })
    return invoices


def financial_years(conn, user: dict) -> list[str]:
    col = "seller_id" if user["role"] == "seller" else "buyer_id"
    rows = conn.execute(f"SELECT created_at, dispatched_at FROM orders WHERE {col}=?", (user["id"],)).fetchall()
    years = {gst.fy_for_date(gst.to_ist_date(r["dispatched_at"] or r["created_at"])) for r in rows}
    years.add(gst.fy_for_date(datetime.now(gst.IST).date()))
    return sorted(years, reverse=True)


def summarize(invoices: list[dict]) -> dict:
    z = Decimal("0")
    s = {"invoices": len(invoices), "taxable": z, "cgst": z, "sgst": z, "igst": z, "total_tax": z, "invoice_value": z,
         "nil_or_no_tax_value": z, "provisional": 0, "warnings": 0}
    for inv in invoices:
        t = inv["tax"]
        s["taxable"] += t["taxable"]
        s["cgst"] += t["cgst"]
        s["sgst"] += t["sgst"]
        s["igst"] += t["igst"]
        s["total_tax"] += t["total_tax"]
        s["invoice_value"] += t["invoice_value"]
        if t["total_tax"] == 0:
            s["nil_or_no_tax_value"] += t["taxable"]
        if inv["basis"].startswith("Provisional"):
            s["provisional"] += 1
        if invoice_warnings(inv):
            s["warnings"] += 1
    return {k: (float(v) if isinstance(v, Decimal) else v) for k, v in s.items()}


def invoice_warnings(inv: dict) -> list[str]:
    out = []
    if not inv["export"] and not inv["pos_code"]:
        out.append("Buyer state is missing; place of supply could not be determined.")
    if inv["basis"].startswith("Provisional"):
        out.append("Order accepted but not yet dispatched; invoice is provisional.")
    if not inv["seller_gstin"] and inv["tax"]["rate"] > 0 and not inv["export"]:
        out.append("Seller has no GSTIN, so GST was not charged on a product that is normally taxable.")
    return out


# ------------------------------------------------------------------ workbook helpers
HEAD_FILL = PatternFill("solid", fgColor="173C2C")
HEAD_FONT = Font(bold=True, color="FFFFFF")
TOTAL_FILL = PatternFill("solid", fgColor="E9F0E4")
THIN = Side(style="thin", color="D5DBD0")
BORDER = Border(left=THIN, right=THIN, top=THIN, bottom=THIN)
MONEY = '#,##0.00'
QTY = '#,##0.000'


def _cell(ws, row, col, value, fmt=None, bold=False, fill=None, wrap=False, formula=False):
    c = ws.cell(row=row, column=col)
    if isinstance(value, Decimal):
        value = float(value)
    c.value = value
    if isinstance(value, str) and value.startswith("=") and not formula:
        c.data_type = "s"  # user-supplied text must never be evaluated as an Excel formula
    if fmt:
        c.number_format = fmt
    if bold:
        c.font = Font(bold=True)
    if fill:
        c.fill = fill
    if wrap:
        c.alignment = Alignment(wrap_text=True, vertical="top")
    return c


def _table(ws, headers, rows, fmts=None, widths=None, start_row=1, total_cols=None, freeze=True):
    fmts = fmts or {}
    for j, h in enumerate(headers, 1):
        c = ws.cell(row=start_row, column=j, value=h)
        c.fill, c.font, c.border = HEAD_FILL, HEAD_FONT, BORDER
        c.alignment = Alignment(wrap_text=True, vertical="center")
    r = start_row
    for r_off, row in enumerate(rows, 1):
        r = start_row + r_off
        for j, v in enumerate(row, 1):
            c = _cell(ws, r, j, v, fmts.get(j))
            c.border = BORDER
    if total_cols and rows:
        r += 1
        _cell(ws, r, 1, "TOTAL", bold=True, fill=TOTAL_FILL)
        for j in range(2, len(headers) + 1):
            ws.cell(row=r, column=j).fill = TOTAL_FILL
        for j in total_cols:
            letter = get_column_letter(j)
            c = _cell(ws, r, j, f"=SUM({letter}{start_row + 1}:{letter}{r - 1})", fmts.get(j), bold=True, fill=TOTAL_FILL, formula=True)
            c.border = BORDER
    for j, h in enumerate(headers, 1):
        ws.column_dimensions[get_column_letter(j)].width = (widths or {}).get(j, max(12, min(34, len(h) + 4)))
    if freeze:
        ws.freeze_panes = ws.cell(row=start_row + 1, column=1)
    ws.row_dimensions[start_row].height = 32
    return r


def _gst_ledger_names(inv: dict, purchase: bool) -> list[tuple[str, Decimal]]:
    """Ledger lines (name, amount) excluding the party ledger."""
    t = inv["tax"]
    pre_main = "Purchase" if purchase else "Sales"
    pre_tax = "Input" if purchase else "Output"
    rate = t["rate"]
    if inv["export"]:
        main = f"{pre_main} - {inv['crop']} (Export, zero rated)"
    elif t["total_tax"] == 0 and rate == 0:
        main = f"{pre_main} - {inv['crop']} (Nil rated)"
    elif t["total_tax"] == 0:
        main = f"{pre_main} - {inv['crop']} (No GST charged)"
    else:
        main = f"{pre_main} - {inv['crop']} @ {rate:g}%"
    lines = [(main, t["taxable"])]
    if t["cgst"]:
        lines.append((f"{pre_tax} CGST @ {t['cgst_rate']:g}%", t["cgst"]))
    if t["sgst"]:
        nm = "UTGST" if t["utgst"] else "SGST"
        lines.append((f"{pre_tax} {nm} @ {t['sgst_rate']:g}%", t["sgst"]))
    if t["igst"]:
        lines.append((f"{pre_tax} IGST @ {t['igst_rate']:g}%", t["igst"]))
    return lines


def build_workbook(member: dict, role: str, invoices: list[dict], fy_label: str, generated_at: datetime | None = None) -> bytes:
    purchase = role == "buyer"
    vtype = "Purchase" if purchase else "Sales"
    generated_at = generated_at or datetime.now(timezone.utc)
    wb = Workbook()

    # ---------------- Summary
    ws = wb.active
    ws.title = "Summary"
    sm = summarize(invoices)
    ws.column_dimensions["A"].width = 38
    ws.column_dimensions["B"].width = 44
    _cell(ws, 1, 1, "Baagh - Business & GST Report", bold=True).font = Font(bold=True, size=15, color="173C2C")
    info = [
        ("Member", member["name"]), ("Member ID", member["member_code"]), ("Role", role.title()),
        ("GSTIN", member.get("gstin") or "Not registered / not provided"),
        ("State", member.get("state") or ""), ("Financial year", f"{fy_label} (1 Apr - 31 Mar)" if fy_label != "All" else "All years"),
        ("Voucher type used for Tally", vtype), ("Generated (UTC)", generated_at.strftime("%Y-%m-%d %H:%M")),
    ]
    r = 3
    for k, v in info:
        _cell(ws, r, 1, k, bold=True)
        _cell(ws, r, 2, v)
        r += 1
    r += 1
    _cell(ws, r, 1, "Totals", bold=True, fill=TOTAL_FILL)
    _cell(ws, r, 2, "", fill=TOTAL_FILL)
    r += 1
    totals = [
        ("Invoices", sm["invoices"], None), ("Taxable value (INR)", sm["taxable"], MONEY),
        ("CGST (INR)", sm["cgst"], MONEY), ("SGST / UTGST (INR)", sm["sgst"], MONEY), ("IGST (INR)", sm["igst"], MONEY),
        ("Total GST (INR)", sm["total_tax"], MONEY), ("Invoice value (INR)", sm["invoice_value"], MONEY),
        ("Value with no GST (nil rated / no registration / export) (INR)", sm["nil_or_no_tax_value"], MONEY),
        ("Provisional invoices (not yet dispatched)", sm["provisional"], None),
        ("Invoices with warnings (see 'Warnings')", sm["warnings"], None),
    ]
    for k, v, fmt in totals:
        _cell(ws, r, 1, k)
        _cell(ws, r, 2, v, fmt)
        ws.cell(row=r, column=2).alignment = Alignment(horizontal="left")
        r += 1
    r += 1
    _cell(ws, r, 1, "Sheets in this file", bold=True)
    r += 1
    sheet_help = [
        ("Tally Voucher Register", f"One row per {vtype.lower()} voucher with GST columns (Tally day-book layout)."),
        ("Tally Ledger Entries", "Double-entry lines (ledger, amount, Dr/Cr) for each voucher, ready to map into Tally."),
        ("Tally Ledger Masters", "Ledgers to create in Tally before importing (parties, sales/purchase, GST ledgers)."),
    ]
    if not purchase:
        sheet_help += [("GSTR-1 B2B", "Invoices to GST-registered buyers (GSTR-1 offline-tool layout)."),
                       ("GSTR-1 B2C", "Invoices to unregistered buyers, with a B2CL / B2CS hint.")]
    sheet_help += [("HSN Summary", "HSN-wise quantity, value and tax (GSTR-1 Table 12 layout)."),
                   ("Nil-Exempt Summary", "Nil-rated and exempt supplies (GSTR-1 Table 8 layout)."),
                   ("Warnings", "Items to fix before using this data for filing.")]
    for k, v in sheet_help:
        _cell(ws, r, 1, k)
        _cell(ws, r, 2, v, wrap=True)
        r += 1
    r += 1
    _cell(ws, r, 1, "Important", bold=True)
    _cell(ws, r + 1, 1, DISCLAIMER, wrap=True)
    ws.merge_cells(start_row=r + 1, start_column=1, end_row=r + 1, end_column=2)
    ws.row_dimensions[r + 1].height = 62

    # ---------------- Tally Voucher Register
    ws = wb.create_sheet("Tally Voucher Register")
    headers = ["Date", "Voucher Type", "Voucher No.", "Order Ref", "Party Name", "Party GSTIN", "Party State",
               "Place of Supply", "Item Description", "HSN", "Quantity", "UQC", "Rate (per kg)", "Taxable Value",
               "GST Rate %", "CGST", "SGST / UTGST", "IGST", "Total GST", "Invoice Value", "Supply Type",
               "Status / Basis", "Narration"]
    rows = []
    for inv in invoices:
        t = inv["tax"]
        party = inv["seller"] if purchase else inv["buyer"]
        pg = inv["seller_gstin"] if purchase else inv["buyer_gstin"]
        pstate = inv["seller_state"] if purchase else (inv["buyer_state"] or "")
        rows.append([inv["date"], vtype, inv["invoice_no"], f"Order #{inv['order_id']}", party, pg, pstate, inv["pos_label"],
                     inv["item"], inv["hsn"], inv["qty"], catalog.UNIT, inv["price"], t["taxable"], t["rate"],
                     t["cgst"], t["sgst"], t["igst"], t["total_tax"], t["invoice_value"], t["supply_type"], inv["basis"],
                     f"{vtype} via Baagh marketplace, order #{inv['order_id']}"])
    fm = {1: "DD-MM-YYYY", 11: QTY, 13: MONEY, 14: MONEY, 15: "0.##", 16: MONEY, 17: MONEY, 18: MONEY, 19: MONEY, 20: MONEY}
    _table(ws, headers, rows, fm, {1: 12, 3: 18, 5: 28, 6: 18, 8: 22, 9: 44, 23: 40}, total_cols=[14, 16, 17, 18, 19, 20])

    # ---------------- Tally Ledger Entries + masters
    ws = wb.create_sheet("Tally Ledger Entries")
    headers = ["Voucher Date", "Voucher Type Name", "Voucher Number", "Ledger Name", "Amount", "Dr/Cr", "Party GSTIN",
               "Place of Supply", "Narration"]
    rows = []
    masters: "OrderedDict[str, dict]" = OrderedDict()

    def master(name, group, gstin="", state="", extra=""):
        masters.setdefault(name, {"group": group, "gstin": gstin, "state": state, "extra": extra})

    for inv in invoices:
        t = inv["tax"]
        party = inv["seller"] if purchase else inv["buyer"]
        pg = inv["seller_gstin"] if purchase else inv["buyer_gstin"]
        pstate = inv["seller_state"] if purchase else (inv["buyer_state"] or "")
        narr = f"{vtype} {inv['item']} {inv['qty']:g} kg @ {inv['price']:g}/kg"
        master(party, "Sundry Creditors" if purchase else "Sundry Debtors", pg, pstate,
               "Regular" if pg else ("Overseas" if inv["export"] else "Unregistered"))
        lines = _gst_ledger_names(inv, purchase)
        # party line: Dr for sales, Cr for purchase (invoice value)
        rows.append([inv["date"], vtype, inv["invoice_no"], party, t["invoice_value"], "Cr" if purchase else "Dr", pg, inv["pos_label"], narr])
        for name, amt in lines:
            rows.append([inv["date"], vtype, inv["invoice_no"], name, amt, "Dr" if purchase else "Cr", pg, inv["pos_label"], narr])
            if name.split(" - ")[0] in ("Sales", "Purchase"):
                master(name, "Purchase Accounts" if purchase else "Sales Accounts", extra=f"HSN {inv['hsn']}")
            else:
                master(name, "Duties & Taxes", extra="GST " + ("Input" if purchase else "Output"))
    _table(ws, headers, rows, {1: "DD-MM-YYYY", 5: MONEY}, {1: 13, 3: 18, 4: 38, 8: 22, 9: 54})
    ws2 = wb.create_sheet("Tally Ledger Masters")
    mrows = [[name, v["group"], v["gstin"], v["state"], v["extra"]] for name, v in masters.items()]
    _table(ws2, ["Ledger Name", "Under (Group)", "GSTIN", "State", "Registration Type / Note"], mrows, None, {1: 44, 2: 22, 3: 20, 4: 26, 5: 28})

    # ---------------- GSTR-1 (seller)
    if not purchase:
        ws = wb.create_sheet("GSTR-1 B2B")
        headers = ["GSTIN/UIN of Recipient", "Receiver Name", "Invoice Number", "Invoice date", "Invoice Value", "Place Of Supply",
                   "Reverse Charge", "Applicable % of Tax Rate", "Invoice Type", "E-Commerce GSTIN", "Rate", "Taxable Value", "Cess Amount"]
        rows = [[i["buyer_gstin"], i["buyer"], i["invoice_no"], i["date"], i["tax"]["invoice_value"], i["pos_label"], "N", "",
                 "Regular B2B", "", i["tax"]["rate"], i["tax"]["taxable"], 0]
                for i in invoices if i["buyer_gstin"] and not i["export"]]
        _table(ws, headers, rows, {4: "DD-MM-YYYY", 5: MONEY, 11: "0.##", 12: MONEY, 13: MONEY}, {1: 20, 2: 28, 3: 18, 6: 22}, total_cols=[5, 12])
        ws = wb.create_sheet("GSTR-1 B2C")
        headers = ["Invoice Number", "Invoice date", "Recipient", "Place Of Supply", "Supply Type", "Invoice Value", "Rate", "Taxable Value",
                   "Suggested table", "Note"]
        rows = []
        for i in invoices:
            if i["buyer_gstin"] or i["export"]:
                continue
            t = i["tax"]
            large = t["supply_type"] == "Inter-state" and t["invoice_value"] > B2CL_THRESHOLD
            rows.append([i["invoice_no"], i["date"], i["buyer"], i["pos_label"], t["supply_type"], t["invoice_value"], t["rate"], t["taxable"],
                         "B2CL (invoice-wise)" if large else "B2CS (state/rate-wise)",
                         "Inter-state to unregistered above Rs 1 lakh (Notif. 12/2024-CT)" if large else ""])
        _table(ws, headers, rows, {2: "DD-MM-YYYY", 6: MONEY, 7: "0.##", 8: MONEY}, {1: 18, 3: 28, 4: 22, 5: 16, 9: 22, 10: 50}, total_cols=[6, 8])
        if not member.get("gstin"):
            _cell(ws, len(rows) + 5, 1, "Note: you have no GSTIN on your Baagh profile. GSTR-1 is only filed by GST-registered sellers.", bold=True)

    # ---------------- HSN Summary
    ws = wb.create_sheet("HSN Summary")
    agg: "OrderedDict[tuple, dict]" = OrderedDict()
    for i in invoices:
        key = (i["hsn"], i["tax"]["rate"])
        a = agg.setdefault(key, {"qty": Decimal("0"), "value": Decimal("0"), "taxable": Decimal("0"), "igst": Decimal("0"), "cgst": Decimal("0"), "sgst": Decimal("0"), "desc": i["crop"]})
        a["qty"] += i["qty"]
        a["value"] += i["tax"]["invoice_value"]
        a["taxable"] += i["tax"]["taxable"]
        a["igst"] += i["tax"]["igst"]
        a["cgst"] += i["tax"]["cgst"]
        a["sgst"] += i["tax"]["sgst"]
    headers = ["HSN", "Description", "UQC", "Total Quantity", "Rate %", "Total Value", "Taxable Value", "Integrated Tax Amount", "Central Tax Amount", "State/UT Tax Amount", "Cess Amount"]
    rows = [[h, a["desc"], f"{catalog.UNIT}-{catalog.UNIT_NAME}", a["qty"], rate, a["value"], a["taxable"], a["igst"], a["cgst"], a["sgst"], 0]
            for (h, rate), a in agg.items()]
    _table(ws, headers, rows, {4: QTY, 5: "0.##", 6: MONEY, 7: MONEY, 8: MONEY, 9: MONEY, 10: MONEY, 11: MONEY}, {1: 10, 2: 18, 3: 20}, total_cols=[4, 6, 7, 8, 9, 10])

    # ---------------- Nil / exempt summary (GSTR-1 table 8 style)
    ws = wb.create_sheet("Nil-Exempt Summary")
    buckets = OrderedDict([
        ("Inter-State supplies to registered persons", Decimal("0")), ("Intra-State supplies to registered persons", Decimal("0")),
        ("Inter-State supplies to unregistered persons", Decimal("0")), ("Intra-State supplies to unregistered persons", Decimal("0")),
    ])
    for i in invoices:
        t = i["tax"]
        if i["export"] or t["rate"] != 0:
            continue
        inter = i["pos_code"] != i["seller_state_code"]
        reg = bool(i["buyer_gstin"])
        key = ("Inter-State" if inter else "Intra-State") + " supplies to " + ("registered" if reg else "unregistered") + " persons"
        buckets[key] += t["taxable"]
    rows = [[k, v, 0, 0] for k, v in buckets.items()]
    _table(ws, ["Description", "Nil Rated Supplies", "Exempted (other than nil rated/non-GST)", "Non-GST Supplies"], rows, {2: MONEY, 3: MONEY, 4: MONEY}, {1: 50, 2: 22, 3: 34, 4: 18}, total_cols=[2, 3, 4])

    # ---------------- Warnings
    ws = wb.create_sheet("Warnings")
    rows = [[i["invoice_no"], i["date"], msg] for i in invoices for msg in invoice_warnings(i)]
    rows += [[i["invoice_no"], i["date"], i["tax"]["flag"]] for i in invoices
             if i["tax"]["flag"] and i["tax"]["flag"] not in invoice_warnings(i)]
    if not rows:
        rows = [["", "", "No warnings."]]
    _table(ws, ["Invoice Number", "Date", "Issue"], rows, {2: "DD-MM-YYYY"}, {1: 20, 3: 100})

    buf = io.BytesIO()
    wb.save(buf)
    return buf.getvalue()
